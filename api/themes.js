/* map preset-wish labels to theme ids. Built from the theme labels (single
   source of truth), plus one alias: the site's default wish "girlfriends
   day" isn't a theme label, so it points at the default blush palette. */
const WISH_TO_THEME = {
  "girlfriends day": "blush",
  ...Object.fromEntries(Object.entries(THEMES).map(([id, t]) => [t.label.toLowerCase(), id])),
};

export function resolveTheme(wish) {
  const slug = String(wish || "").trim().toLowerCase();
  return THEMES[WISH_TO_THEME[slug]] || THEMES.blush;
}
